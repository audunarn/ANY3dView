"""Writing results out: a Markdown summary and CSV field dumps.

Both go through the headless layer, so a report is scriptable and does not
need the application open.  The report states what it was asked for and what
the solver reported; it does not editorialise about whether the answer is
acceptable, which is the engineer's call.
"""

